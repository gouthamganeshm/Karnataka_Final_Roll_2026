"""Proof table: the live site's elector count per AC against the CEO's own figure.

    python scripts/home/official_match.py        # writes docs/proof/official-match.md

Reads the live site's data/manifest.json (exactly what visitors' browsers
load) and reference/ceo-final-2026.json (typed from the CEO Karnataka's
AC-wise final-roll booklet), and lists every AC with both numbers and the
difference, grouped by district. No EPIC is involved: counts only.
"""
from __future__ import annotations

import json
import sys
import urllib.request
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SITE = 'https://gouthamganeshm.github.io/Karnataka_Final_Roll_2026/'
OUT = ROOT / 'docs' / 'proof' / 'official-match.md'


def ind(n: int) -> str:
    """Indian digit grouping: 4,54,55,689."""
    s = str(n)
    if len(s) <= 3:
        return s
    head, tail = s[:-3], s[-3:]
    parts = []
    while len(head) > 2:
        parts.insert(0, head[-2:])
        head = head[:-2]
    return ','.join(([head] if head else []) + parts + [tail])


def main() -> int:
    with urllib.request.urlopen(SITE + 'data/manifest.json') as r:
        m = json.load(r)
    ref = json.loads((ROOT / 'reference' / 'ceo-final-2026.json').read_text('utf8'))
    by_district = defaultdict(list)
    for a in m['acs']:
        by_district[a['district']].append(a)
    site_total = sum(a['electors'] for a in m['acs'])
    ceo_total = sum(v['electors'] for v in ref['acs'].values())
    exact = sum(a['electors'] == ref['acs'][str(a['ac'])]['electors'] for a in m['acs'])
    lines = [
        '# Proof: live site vs the CEO\'s official count',
        '',
        f'Generated by `scripts/home/official_match.py` from the live site\'s `data/manifest.json` '
        f'(built {m["builtAt"]}) and the CEO Karnataka booklet '
        f'([PDF]({ref["source"]}), published {ref["published"]}, typed into '
        f'`reference/ceo-final-2026.json`).',
        '',
        '"Site" is the number of live (not deleted) elector cards a visitor can find on the site. '
        '"CEO" is the general-elector total in the booklet (service electors are not in the booth '
        'rolls, so they are not in either column).',
        '',
        '| | Site | CEO booklet | Difference |',
        '|---|---:|---:|---:|',
        f'| **Karnataka, {len(m["acs"])} ACs** | **{ind(site_total)}** | **{ind(ceo_total)}** | '
        f'**{site_total - ceo_total:+d}** |',
        '',
        f'**{exact} of {len(m["acs"])} ACs match exactly.** Cards struck off with a DELETED stamp '
        f'({ind(m["deleted"])} statewide) are searchable on the site but are not counted as electors.',
        '',
    ]
    for district in sorted(by_district):
        acs = sorted(by_district[district], key=lambda a: a['ac'])
        lines += [f'## {district.title()}', '', '| AC | Name | Booths | Site | CEO booklet | Diff | Deleted cards |',
                  '|---:|---|---:|---:|---:|---:|---:|']
        for a in acs:
            ceo = ref['acs'][str(a['ac'])]['electors']
            lines.append(f'| {a["ac"]} | {a["name"]} | {a["parts"]} | {ind(a["electors"])} | {ind(ceo)} | '
                         f'{a["electors"] - ceo:+d} | {ind(a["deleted"])} |')
        lines.append('')
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(lines), 'utf8')
    print(f'{exact}/{len(m["acs"])} exact; site {site_total} vs CEO {ceo_total} -> {OUT}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
